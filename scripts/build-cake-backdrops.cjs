'use strict';
// Read photograph edge colours to build CSS backgrounds. Source pixels stay unchanged.
const fs=require('node:fs');
const path=require('node:path');
const {chromium}=require('@playwright/test');
const root=path.resolve(__dirname,'..');
const manifest=require('../data/cake-background-manifest.json');
(async()=>{
 const browser=await chromium.launch({channel:'msedge',headless:true});
 try{
  const page=await browser.newPage();
  const rules=['/* Generated by scripts/build-cake-backdrops.cjs; colours sampled from photo edges. */'];
  for(const record of manifest.images.filter(r=>r.status==='applied')){
   const source='data:image/webp;base64,'+fs.readFileSync(path.join(root,record.image)).toString('base64');
   const gradients=await page.evaluate(async src=>{
    const photo=new Image();photo.src=src;await photo.decode();
    const canvas=document.createElement('canvas');canvas.width=photo.naturalWidth;canvas.height=photo.naturalHeight;
    const context=canvas.getContext('2d',{willReadFrequently:true});context.drawImage(photo,0,0);
    return ['left','right'].map(side=>{
     const stops=[];
     for(let n=0;n<=16;n++){
      const y=Math.min(canvas.height-5,Math.max(0,Math.round(n/16*(canvas.height-1))-2));
      const pixels=context.getImageData(side==='left'?0:canvas.width-3,y,3,5).data;
      const channels=[0,0,0];
      for(let i=0;i<pixels.length;i+=4)for(let c=0;c<3;c++)channels[c]+=pixels[i+c];
      const rgb=channels.map(v=>Math.round(v/(pixels.length/4))).join(',');
      stops.push('rgb('+rgb+') '+(n/16*100)+'%');
     }
     return 'linear-gradient('+stops.join(',')+') '+side+' / 50.1% 100% no-repeat';
    }).join(',');
   },source);
   rules.push('img.cake-image[src*="'+path.basename(record.image)+'"]{--cake-backdrop:'+gradients+'}');
  }
  fs.writeFileSync(path.join(root,'assets/css/cake-backdrops.css'),rules.join('\n')+'\n');
  console.log('Built CSS backdrops for '+(rules.length-1)+' cake photos.');
 }finally{await browser.close();}
})().catch(error=>{console.error(error);process.exitCode=1;});
